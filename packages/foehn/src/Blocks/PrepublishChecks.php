<?php

declare(strict_types=1);

namespace Studiometa\Foehn\Blocks;

use Studiometa\Foehn\Config\FoehnConfig;
use Studiometa\Foehn\Discovery\BlockDiscovery;
use Studiometa\Foehn\Discovery\DiscoveryRunner;

/**
 * Ships the accessibility checks of the pre-publish panel to the block editor.
 *
 * The script is static and generic, like the block registrar: the installer copies
 * it into the web root. What it reads is printed before it, as
 * `window.foehnPrepublishChecks`: for each Føhn block, the attributes that hold an
 * image (`image` and `gallery` controls) and those that hold a heading level
 * (`headingLevel` control), and whether the issues block publication.
 */
final readonly class PrepublishChecks
{
    /** Script handle of the checks and of their inline configuration. */
    public const string HANDLE = 'foehn-prepublish-checks';

    /** Path of the script, relative to the WordPress content directory. */
    private const string SCRIPT_PATH = 'foehn/prepublish-checks.js';

    /**
     * WordPress script handles the checks read their globals from.
     *
     * @var list<string>
     */
    private const array DEPENDENCIES = [
        'wp-blocks',
        'wp-components',
        'wp-data',
        'wp-editor',
        'wp-element',
        'wp-hooks',
        'wp-plugins',
    ];

    /** Controls whose attribute holds attachment ids of images. */
    private const array IMAGE_CONTROLS = ['image', 'gallery'];

    public function __construct(
        private DiscoveryRunner $runner,
        private FoehnConfig $config,
    ) {}

    /**
     * Enqueue the checks with their configuration inlined before them.
     *
     * Handler for the `enqueue_block_editor_assets` action. WordPress also fires it
     * on the block widgets screen and in the Customizer, where `wp-editor` must not
     * load: only the block post editor gets the checks. A missing script is skipped,
     * with a warning in debug mode.
     */
    public function enqueue(): void
    {
        if (!$this->isPostEditor()) {
            return;
        }

        $path = constant('WP_CONTENT_DIR') . '/' . self::SCRIPT_PATH;

        if (!is_file($path)) {
            if ($this->config->isDebugEnabled()) {
                trigger_error(
                    sprintf(
                        '[Foehn] Pre-publish checks script not found at "%s". It is generated by `composer install`.',
                        $path,
                    ),
                    E_USER_WARNING,
                );
            }

            return;
        }

        $json = wp_json_encode([
            'blockPublication' => $this->config->blockPublicationOnAccessibilityIssues,
            'blocks' => (object) $this->getBlocks(),
        ]);

        if ($json === false) {
            return;
        }

        wp_enqueue_script(
            self::HANDLE,
            content_url(self::SCRIPT_PATH),
            self::DEPENDENCIES,
            (string) filemtime($path),
            true,
        );
        wp_add_inline_script(self::HANDLE, 'window.foehnPrepublishChecks = ' . $json . ';', 'before');
    }

    /**
     * Whether the current screen is the block post editor.
     *
     * `get_current_screen()` is only defined in the admin, so its absence is a "no".
     */
    private function isPostEditor(): bool
    {
        if (!function_exists('get_current_screen')) {
            return false;
        }

        $screen = get_current_screen();

        return $screen !== null && $screen->base === 'post' && $screen->is_block_editor();
    }

    /**
     * The image and heading level attributes of each Føhn block that has one.
     *
     * @return array<string, array{images: object, headings: list<string>}>
     */
    private function getBlocks(): array
    {
        $discovery = $this->runner->getDiscoveries()[BlockDiscovery::class] ?? null;

        if (!$discovery instanceof BlockDiscovery) {
            return [];
        }

        $blocks = [];

        foreach ($discovery->getEditorDefinitions() as $definition) {
            $images = [];
            $headings = [];

            /** @var array{control: string|null, label: string} $field */
            foreach ($definition['attributes'] as $name => $field) {
                if (in_array($field['control'], self::IMAGE_CONTROLS, true)) {
                    $images[$name] = $field['label'];
                }

                if ($field['control'] === 'headingLevel') {
                    $headings[] = $name;
                }
            }

            if ($images === [] && $headings === []) {
                continue;
            }

            // An object, so an empty map is `{}` and not `[]` in the JSON.
            $blocks[$definition['name']] = ['images' => (object) $images, 'headings' => $headings];
        }

        return $blocks;
    }
}
